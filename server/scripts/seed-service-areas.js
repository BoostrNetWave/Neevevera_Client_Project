async function seedServiceAreas() {
  try {
    const mongoUri = process.env.MONGO_URI;
    if (!mongoUri) {
      throw new Error('MONGO_URI is missing from environment.');
    }

    console.log('Connecting to MongoDB...');
    await mongoose.connect(mongoUri);
    console.log('Connected to MongoDB.');

    console.log(`Seeding ${SEED_AREAS.length} verified service areas across Cuttack, Khordha, and Andaman & Nicobar...`);

    const ops = SEED_AREAS.map((area) => ({
      updateOne: {
        filter: { pincode: area.pincode },
        update: { $set: area },
        upsert: true,
      },
    }));

    const result = await ServiceArea.bulkWrite(ops);

    console.log(`✅ Upserted: ${result.upsertedCount}, Modified: ${result.modifiedCount}`);
    console.log('✅ Full service area seed completed successfully.');
  } catch (err) {
    console.error('❌ Failed to seed service areas:', err);
  } finally {
    await mongoose.disconnect();
    console.log('Disconnected from MongoDB.');
  }
}

seedServiceAreas();
